import "dotenv/config";
import express from "express";
import cors from "cors";
import healthRouter from "./routes/health.routes.js";
import authRouter from "./routes/auth.routes.js";
import { initializeAuth } from "./services/auth.service.js";
import analyzeRouter from "./routes/analyze.routes.js";
const app=express(), PORT=Number(process.env.PORT||3001);
app.use(cors({origin:process.env.CORS_ORIGIN||"*"}));
app.use(express.json({limit:"2mb"}));
app.use("/api/health",healthRouter);
app.use("/api/auth",authRouter);
app.use("/api",analyzeRouter);
app.use((err,req,res,next)=>{
  console.error('[AcessForge backend]', err?.message || err);
  const status = Number.isInteger(err?.status) ? err.status : 500;
  res.status(status).json({ ok: false, error: err?.code || 'INTERNAL_ERROR', message: status >= 500 && status !== 503 ? (err?.message || 'Erro interno no backend.') : err.message });
});
await initializeAuth();
app.listen(PORT,()=>console.log(`AcessForge backend running on http://localhost:${PORT}`));